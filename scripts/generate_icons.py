#!/usr/bin/env python3
"""Generates the adaptive launcher icon and the notification icon for a site (spec R9).

Three icon sources, chosen by which key the site config sets:
  ICON_SVG     single-color glyph SVG (best: crisp, themed-icon and notification ready)
  ICON_RASTER  square PNG/WebP, e.g. a web-manifest icon (ICON_RASTER_MASKABLE for maskable icons)
  ICON_LETTER  a letter or digit drawn from scripts/letter_glyphs.json (DejaVu Sans Bold)

Normally run by site_config.py during the Gradle build. Standard library only.

    python3 scripts/generate_icons.py --site discord --res-out /tmp/res   # generate
    python3 scripts/generate_icons.py --verify template/build/generated/...    # check generated pathData
"""

import argparse
import json
import re
import shutil
import struct
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

GLYPHS = Path(__file__).resolve().parent / "letter_glyphs.json"
REQUIRED_FILES = [
    "drawable/ic_launcher_background.xml",
    "drawable/ic_launcher_foreground.xml",
    "drawable/ic_stat_notify.xml",
    "mipmap-anydpi/ic_launcher.xml",
    "mipmap-anydpi/ic_launcher_round.xml",
]

ARITY = {"M": 2, "L": 2, "H": 1, "V": 1, "C": 6, "S": 4, "Q": 4, "T": 2, "A": 7, "Z": 0}
COMMANDS = "MmLlHhVvCcSsQqTtAaZz"
NUMBER = re.compile(r"[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?")
HEX_COLOR = re.compile(r"^#[0-9A-Fa-f]{6}$")
# Built from pieces so this file never contains the placeholder markers it checks for.
PLACEHOLDER_MARKERS = ("<" * 2, ">" * 2)
GLYPH_ONLY = "ICON_SVG must be a single-color glyph made only of <path> elements"
# Elements that may appear besides <svg>/<g>/<path>; their content is ignored.
IGNORED_ELEMENTS = {"title", "desc", "metadata"}
HEADER = "<!-- Generated by scripts/generate_icons.py from the site config. Do not edit by hand. -->"
ANDROID_NS = "http://schemas.android.com/apk/res/android"

# Raster placement inside the 108dp adaptive canvas. A maskable icon keeps its essential
# content in the central 80% circle; scaling the icon to 90dp maps that circle onto the
# 72dp visible area. Other icons are fitted into the 66dp safe zone.
RASTER_INSET_MASKABLE_DP = 9
RASTER_INSET_ANY_DP = 21
MIN_RASTER_PX = 192
LETTER_SIZE = 40   # glyph's larger side, in the 108-unit launcher viewport
NOTIFY_SIZE = 20   # glyph's larger side, in the 24-unit notification viewport


class IconError(Exception):
    pass


# ---------- SVG source (R9.3) ----------

def local_name(tag):
    return tag.rsplit("}", 1)[-1]


def style_props(element):
    props = {}
    for declaration in (element.get("style") or "").split(";"):
        if ":" in declaration:
            key, value = declaration.split(":", 1)
            props[key.strip().lower()] = value.strip()
    return props


def presentation(element, name, inherited):
    value = style_props(element).get(name, element.get(name))
    return inherited if value in (None, "", "inherit") else value.strip()


def parse_svg(data):
    """Returns ((min_x, min_y, width, height), [path d strings], fill_rule) for a glyph SVG."""
    try:
        root = ET.fromstring(data)
    except ET.ParseError as exc:
        raise IconError(f"ICON_SVG is not valid XML: {exc}") from exc
    if local_name(root.tag) != "svg":
        raise IconError("ICON_SVG root element is not <svg>")

    view_box = root.get("viewBox")
    if not view_box:
        raise IconError("ICON_SVG has no viewBox")
    try:
        min_x, min_y, width, height = (float(v) for v in re.split(r"[\s,]+", view_box.strip()))
    except ValueError as exc:
        raise IconError(f"invalid viewBox {view_box!r}") from exc
    if width <= 0 or height <= 0:
        raise IconError(f"invalid viewBox {view_box!r}")

    paths = []

    def walk(element, fill, fill_rule):
        name = local_name(element.tag)
        if name in IGNORED_ELEMENTS:
            return
        if name not in ("svg", "g", "path"):
            raise IconError(f"{GLYPH_ONLY} (found <{name}>)")
        if element.get("transform") or "transform" in style_props(element):
            raise IconError(f"{GLYPH_ONLY} (transform on <{name}>)")
        fill = presentation(element, "fill", fill)
        fill_rule = presentation(element, "fill-rule", fill_rule)
        if name == "path":
            d = (element.get("d") or "").strip()
            if fill == "none":
                raise IconError(f"{GLYPH_ONLY} (stroke-only or unfilled <path>)")
            if fill.startswith("url("):
                raise IconError(f"{GLYPH_ONLY} (gradient or pattern fill)")
            if d:
                paths.append((d, fill_rule))
        for child in element:
            walk(child, fill, fill_rule)

    walk(root, "black", "nonzero")
    if not paths:
        raise IconError("ICON_SVG contains no <path d> data")
    even_odd = any(rule == "evenodd" for _, rule in paths)
    return (min_x, min_y, width, height), [d for d, _ in paths], "evenodd" if even_odd else "nonzero"


# ---------- Android PathParser normalization (R9.4) ----------

def tokenize(d):
    """Arc-flag-aware tokenizer: command letters as str, parameters as float."""
    tokens, i, command, index = [], 0, None, 0
    while i < len(d):
        ch = d[i]
        if ch.isspace() or ch == ",":
            i += 1
            continue
        if ch in COMMANDS:
            tokens.append(ch)
            command, index, i = ch, 0, i + 1
            continue
        if command is None:
            raise IconError(f"path data must start with a command (offset {i})")
        if command in "Aa" and index % 7 in (3, 4):
            if ch not in "01":
                raise IconError(f"invalid arc flag {ch!r} at offset {i}")
            tokens.append(float(ch))
            index, i = index + 1, i + 1
            continue
        match = NUMBER.match(d, i)
        if not match:
            raise IconError(f"unexpected {ch!r} in path data at offset {i}")
        tokens.append(float(match.group()))
        index, i = index + 1, match.end()
    return tokens


def to_groups(tokens):
    """Splits into (command, params) groups with an explicit command letter per group."""
    groups, i = [], 0
    while i < len(tokens):
        command = tokens[i]
        i += 1
        params = []
        while i < len(tokens) and not isinstance(tokens[i], str):
            params.append(tokens[i])
            i += 1
        arity = ARITY[command.upper()]
        if arity == 0:
            if params:
                raise IconError(f"command {command} takes no parameters")
            groups.append((command, []))
            continue
        if not params or len(params) % arity:
            raise IconError(f"command {command} has {len(params)} parameters; expected a multiple of {arity}")
        for k in range(0, len(params), arity):
            letter = command
            if k and command in "Mm":
                letter = "L" if command == "M" else "l"
            groups.append((letter, params[k:k + arity]))
    if groups and groups[0][0] == "m":
        # The first moveto of a path is absolute even when written lowercase; keep that
        # meaning when several <path> elements are concatenated.
        groups[0] = ("M", groups[0][1])
    return groups


def fmt(value):
    text = f"{value:.4f}".rstrip("0").rstrip(".")
    return "0" if text in ("", "-", "-0") else text


def serialize(groups):
    parts = []
    for command, params in groups:
        parts.append(command)
        for index, value in enumerate(params):
            if command in "Aa" and index in (3, 4):
                parts.append("1" if value else "0")
            else:
                parts.append(fmt(value))
    return " ".join(parts)


def android_safe_path(path_list):
    return " ".join(serialize(to_groups(tokenize(d))) for d in path_list)


# ---------- Raster source ----------

def raster_info(data):
    """Returns (extension, width, height) for a PNG or WebP image."""
    if data[:8] == b"\x89PNG\r\n\x1a\n" and data[12:16] == b"IHDR":
        width, height = struct.unpack(">II", data[16:24])
        return "png", width, height
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        chunk = data[12:16]
        if chunk == b"VP8X":
            width = 1 + int.from_bytes(data[24:27], "little")
            height = 1 + int.from_bytes(data[27:30], "little")
        elif chunk == b"VP8L":
            bits = int.from_bytes(data[21:25], "little")
            width, height = 1 + (bits & 0x3FFF), 1 + ((bits // 0x4000) & 0x3FFF)  # 14-bit fields
        elif chunk == b"VP8 ":
            width = int.from_bytes(data[26:28], "little") & 0x3FFF
            height = int.from_bytes(data[28:30], "little") & 0x3FFF
        else:
            raise IconError("unsupported WebP variant")
        return "webp", width, height
    raise IconError("ICON_RASTER must be a PNG or WebP image")


# ---------- Letter source ----------

def letter_glyph(letter):
    glyphs = json.loads(GLYPHS.read_text(encoding="utf-8"))["glyphs"]
    glyph = glyphs.get(letter.upper())
    if glyph is None:
        raise IconError(f"no glyph for ICON_LETTER {letter!r} (A-Z and 0-9 are available)")
    return glyph


def fit_transform(bbox, size, center):
    """Scale and translation that fit bbox (x0, y0, x1, y1) into a size x size box at center."""
    x0, y0, x1, y1 = bbox
    scale = size / max(x1 - x0, y1 - y0)
    return scale, center - (x0 + x1) / 2 * scale, center - (y0 + y1) / 2 * scale


# ---------- XML writers ----------

def vector(width_dp, height_dp, viewport_w, viewport_h, body):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"{HEADER}\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{width_dp}dp"\n'
        f'    android:height="{height_dp}dp"\n'
        f'    android:viewportWidth="{fmt(viewport_w)}"\n'
        f'    android:viewportHeight="{fmt(viewport_h)}">\n'
        f"{body}"
        "</vector>\n"
    )


def path_element(fill, path_data, fill_type, indent):
    pad = " " * indent
    return (
        f"{pad}<path\n"
        f'{pad}    android:fillColor="{fill}"\n'
        f'{pad}    android:fillType="{fill_type}"\n'
        f'{pad}    android:pathData="{path_data}" />\n'
    )


def group(scale, translate_x, translate_y, inner):
    return (
        "    <group\n"
        f'        android:scaleX="{fmt(scale)}"\n'
        f'        android:scaleY="{fmt(scale)}"\n'
        f'        android:translateX="{fmt(translate_x)}"\n'
        f'        android:translateY="{fmt(translate_y)}">\n'
        f"{inner}"
        "    </group>\n"
    )


def adaptive_icon(monochrome):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"{HEADER}\n"
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@drawable/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        f'    <monochrome android:drawable="@drawable/{monochrome}" />\n'
        "</adaptive-icon>\n"
    )


def write(res_dir, relative, content):
    path = res_dir / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(content, bytes):
        path.write_bytes(content)
    else:
        path.write_text(content, encoding="utf-8")


def letter_vectors(letter, foreground):
    """(launcher foreground body, notification body) for a letter glyph."""
    glyph = letter_glyph(letter)
    path_data = android_safe_path([glyph["d"]])
    scale, tx, ty = fit_transform(glyph["bbox"], LETTER_SIZE, 54)
    launcher = group(scale, tx, ty, path_element(foreground, path_data, "nonZero", 8))
    scale, tx, ty = fit_transform(glyph["bbox"], NOTIFY_SIZE, 12)
    notify = group(scale, tx, ty, path_element("#FFFFFF", path_data, "nonZero", 8))
    return launcher, notify


# ---------- Generation (R9.1, R9.6) ----------

def generate(c, site_dir, res_dir):
    """Writes the launcher and notification icons for resolved site config c into res_dir."""
    background, foreground = c["ICON_BACKGROUND_HEX"], c["ICON_FOREGROUND_HEX"]
    for name, value in (("ICON_BACKGROUND_HEX", background), ("ICON_FOREGROUND_HEX", foreground)):
        if not HEX_COLOR.match(value):
            raise IconError(f"{name} must be #RRGGBB, got {value!r}")
    # R9.1: start from a clean slate so reruns are idempotent.
    for directory in list(res_dir.glob("mipmap-*")) + list(res_dir.glob("drawable*")):
        shutil.rmtree(directory)

    write(res_dir, "drawable/ic_launcher_background.xml", vector(
        108, 108, 108, 108, path_element(background, "M 0 0 H 108 V 108 H 0 Z", "nonZero", 4)))
    mode = c["ICON_MODE"]
    monochrome = "ic_launcher_foreground"

    if mode == "svg":
        (min_x, min_y, width, height), paths, rule = parse_svg((site_dir / c["ICON_SVG"]).read_bytes())
        path_data = android_safe_path(paths)
        fill_type = "evenOdd" if rule == "evenodd" else "nonZero"
        scale = 54 / max(width, height)
        write(res_dir, "drawable/ic_launcher_foreground.xml", vector(108, 108, 108, 108, group(
            scale,
            54 - (min_x + width / 2) * scale,
            54 - (min_y + height / 2) * scale,
            path_element(foreground, path_data, fill_type, 8),
        )))
        if min_x or min_y:
            notify = (
                "    <group\n"
                f'        android:translateX="{fmt(-min_x)}"\n'
                f'        android:translateY="{fmt(-min_y)}">\n'
                f"{path_element('#FFFFFF', path_data, fill_type, 8)}"
                "    </group>\n"
            )
        else:
            notify = path_element("#FFFFFF", path_data, fill_type, 4)
        write(res_dir, "drawable/ic_stat_notify.xml", vector(24, 24, width, height, notify))
        summary = f"svg scale={fmt(scale)} fillType={fill_type}"

    elif mode == "raster":
        data = (site_dir / c["ICON_RASTER"]).read_bytes()
        ext, width, height = raster_info(data)
        if width != height:
            raise IconError(f"ICON_RASTER must be square, got {width}x{height}")
        if width < MIN_RASTER_PX:
            raise IconError(f"ICON_RASTER must be at least {MIN_RASTER_PX}px, got {width}px")
        write(res_dir, f"drawable-nodpi/ic_launcher_raster.{ext}", data)
        inset = RASTER_INSET_MASKABLE_DP if c["ICON_RASTER_MASKABLE"] else RASTER_INSET_ANY_DP
        write(res_dir, "drawable/ic_launcher_foreground.xml", (
            '<?xml version="1.0" encoding="utf-8"?>\n'
            f"{HEADER}\n"
            '<inset xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:drawable="@drawable/ic_launcher_raster"\n'
            f'    android:inset="{inset}dp" />\n'
        ))
        # A colored bitmap cannot be a themed or status-bar icon; use the app's letter for those.
        letter = next((ch for ch in c["APP_NAME"].upper() if ch.isascii() and ch.isalnum()), "A")
        launcher, notify = letter_vectors(letter, "#FFFFFF")
        write(res_dir, "drawable/ic_launcher_monochrome.xml", vector(108, 108, 108, 108, launcher))
        write(res_dir, "drawable/ic_stat_notify.xml", vector(24, 24, 24, 24, notify))
        monochrome = "ic_launcher_monochrome"
        summary = f"raster {ext} {width}px inset={inset}dp monochrome=letter {letter}"
        if width < 432:
            print(f"warning: ICON_RASTER is {width}px; 432px or more avoids blur on xxxhdpi screens", file=sys.stderr)

    elif mode == "letter":
        launcher, notify = letter_vectors(c["ICON_LETTER"], foreground)
        write(res_dir, "drawable/ic_launcher_foreground.xml", vector(108, 108, 108, 108, launcher))
        write(res_dir, "drawable/ic_stat_notify.xml", vector(24, 24, 24, 24, notify))
        summary = f"letter {c['ICON_LETTER'].upper()}"
    else:
        raise IconError(f"unknown icon mode {mode!r}")

    write(res_dir, "mipmap-anydpi/ic_launcher.xml", adaptive_icon(monochrome))
    write(res_dir, "mipmap-anydpi/ic_launcher_round.xml", adaptive_icon(monochrome))
    print(f"icons: {summary} background={background} foreground={foreground}", file=sys.stderr)


# ---------- Verification (R9.5) ----------

def check_path_data(path_data):
    errors = []
    if re.search(r"(^|[\s-])\.\d", path_data):
        errors.append("number with a bare leading '.'")
    if re.search(r"[eE]", path_data):
        errors.append("exponent notation")
    tokens = path_data.split(" ")
    if path_data != path_data.strip() or "" in tokens:
        errors.append("tokens must be separated by exactly one space")
        return errors
    i = 0
    while i < len(tokens):
        command = tokens[i]
        if len(command) != 1 or command not in COMMANDS:
            errors.append(f"token {i}: expected a command letter, got {command!r}")
            break
        arity = ARITY[command.upper()]
        params = tokens[i + 1:i + 1 + arity]
        if len(params) != arity or not all(re.fullmatch(r"-?\d+(\.\d+)?", p) for p in params):
            errors.append(f"token {i}: {command} needs {arity} numeric parameters, got {params!r}")
            break
        if command in "Aa" and (params[3] not in ("0", "1") or params[4] not in ("0", "1")):
            errors.append(f"token {i}: arc flags must be 0 or 1, got {params[3]!r} {params[4]!r}")
        i += 1 + arity
    return errors


def verify(res_dir):
    failures = []
    for relative in REQUIRED_FILES:
        if not (res_dir / relative).is_file():
            failures.append(f"{relative}: missing")
    files = sorted(res_dir.glob("drawable*/*.xml")) + sorted(res_dir.glob("mipmap-*/*.xml"))
    for path in files:
        relative = path.relative_to(res_dir)
        text = path.read_text(encoding="utf-8")
        try:
            root = ET.fromstring(text)
        except ET.ParseError as exc:
            failures.append(f"{relative}: invalid XML ({exc})")
            continue
        for marker in PLACEHOLDER_MARKERS:
            if marker in text:
                failures.append(f"{relative}: contains placeholder marker {marker!r}")
        for path_data in re.findall(r'android:pathData="([^"]*)"', text):
            failures.extend(f"{relative}: {error}" for error in check_path_data(path_data))
        if local_name(root.tag) == "inset":
            target = root.get(f"{{{ANDROID_NS}}}drawable", "").removeprefix("@drawable/")
            if not list(res_dir.glob(f"drawable*/{target}.*")):
                failures.append(f"{relative}: inset drawable @drawable/{target} does not exist")
    if failures:
        print("verify FAILED:", *failures, sep="\n  ", file=sys.stderr)
        return 1
    print(f"verify OK: {len(files)} files")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--verify", type=Path, metavar="RES_DIR", help="check generated icon XML in RES_DIR")
    parser.add_argument("--site", help="site id to generate icons for")
    parser.add_argument("--res-out", type=Path, help="resource directory to write")
    args = parser.parse_args()
    try:
        if args.verify:
            return verify(args.verify)
        if not (args.site and args.res_out):
            parser.error("--site and --res-out are required unless --verify is given")
        import site_config

        c = site_config.load(args.site)
        args.res_out.mkdir(parents=True, exist_ok=True)
        generate(c, Path(c["SITE_DIR"]), args.res_out)
        return 0
    except IconError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
